/**
 * @vitest-environment jsdom
 */
import { describe, expect, it, vi } from 'vitest'
import { render, screen } from '@testing-library/react'
import i18n from '../../translations/i18n'
import AssistantBox from './AssistantBox'

vi.mock('../../context/ConfigurationProvider', () => ({
  useConfiguration: () => ({ configuration: { languages: [] } }),
}))

vi.mock('../../hooks/api/ai', () => ({
  useAiApi: () => ({ generateText: vi.fn() }),
}))

vi.mock('@emporix/component-library', async () => {
  const actual = await vi.importActual<
    typeof import('@emporix/component-library')
  >('@emporix/component-library')
  return {
    ...actual,
    useToast: () => ({ showError: vi.fn() }),
  }
})

const productName = { en: 'Chair' }

const renderAssistant = () =>
  render(
    <AssistantBox
      productName={productName}
      visible
      onAccept={() => undefined}
      onReject={() => undefined}
    />
  )

describe('AssistantBox AI notice', () => {
  it('shows the English short notice and leaves generate under the current rules', async () => {
    await i18n.changeLanguage('en')
    renderAssistant()

    const notice = screen.getByText(
      'NOTE: Output is generated by AI. Please verify as errors may occur.'
    )
    expect(notice.closest('[data-severity="info"]')).toBeTruthy()
    const generate = screen.getByRole('button', {
      name: 'Generate descriptions',
    })
    expect((generate as HTMLButtonElement).disabled).toBe(true)
  })

  it('shows the German short notice', async () => {
    await i18n.changeLanguage('de')
    renderAssistant()

    const notice = screen.getByText(
      'HINWEIS: Die Ausgabe wird von KI erzeugt. Bitte prüfen Sie sie, da Fehler auftreten können.'
    )
    expect(notice.closest('[data-severity="info"]')).toBeTruthy()
    await i18n.changeLanguage('en')
  })
})
