import { describe, expect, it } from 'vitest'
import { renderToStaticMarkup } from 'react-dom/server'
import '../../translations/i18n'
import { AiGeneratedNotice } from './AiGeneratedNotice'
import styles from './AiGeneratedNotice.module.scss'

describe('AiGeneratedNotice', () => {
  it('renders the long notice with the detail placement class', () => {
    const markup = renderToStaticMarkup(
      <AiGeneratedNotice variant="long" placement="detail" />
    )

    expect(markup).toContain(
      'An agent will generate content using artificial intelligence.'
    )
    expect(markup).toContain('data-severity="info"')
    expect(markup).toContain('role="status"')
    expect(markup).toContain(styles.notice)
    expect(markup).toContain(styles.detail)
  })

  it('renders the short notice with the dialog placement class', () => {
    const markup = renderToStaticMarkup(
      <AiGeneratedNotice variant="short" placement="dialog" />
    )

    expect(markup).toContain(
      'NOTE: Output is generated by AI. Please verify as errors may occur.'
    )
    expect(markup).toContain(styles.dialog)
  })
})
